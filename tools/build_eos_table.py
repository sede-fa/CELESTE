"""
Build celeste/data/eos_species.csv: critical constants and Mathias-Copeman alpha
parameters for the Peng-Robinson equation of state used by celeste.jx.eos.

Critical temperature, critical pressure and acentric factor are read from the
reference equations of state shipped with CoolProp. The three Mathias-Copeman
parameters are fitted so that the Peng-Robinson equation reproduces the
saturation pressure of the reference equation between the triple point (or
T_r = 0.45) and T_r = 0.99.

This script is a development tool (it needs CoolProp and SciPy); the generated
table is committed, so running it is only necessary to add species:

    python tools/build_eos_table.py
"""
from pathlib import Path

import numpy as np
import CoolProp.CoolProp as CP
from scipy.optimize import brentq

R = 8.314462618e-5          # bar m3 / mol / K
S2 = np.sqrt(2.0)

# celeste name, CoolProp name, name in the NASA database
SPECIES = [
    ("H2", "Hydrogen", "H2"), ("N2", "Nitrogen", "N2"), ("O2", "Oxygen", "O2"), ("Ar", "Argon", "Ar"),
    ("CO", "CarbonMonoxide", "CO"), ("CO2", "CarbonDioxide", "CO2"), ("H2O", "Water", "H2O"),
    ("NH3", "Ammonia", "NH3"), ("CH4", "Methane", "CH4"), ("C2H6", "Ethane", "C2H6"),
    ("C2H4", "Ethylene", "C2H4"), ("C3H8", "n-Propane", "C3H8"), ("C4H10", "n-Butane", "C4H10,n-butane"),
    ("CH3OH", "Methanol", "CH3OH"), ("C2H5OH", "Ethanol", "C2H5OH"), ("CH3OCH3", "DimethylEther", "CH3OCH3"),
]


def ln_phi_pure(Z, A, B):
    return Z - 1 - np.log(Z - B) - A/(2*S2*B)*np.log((Z + (1 + S2)*B)/(Z + (1 - S2)*B))


def fugacity_gap(alpha, T, P, Tc, Pc):
    """ln(phi_liquid) - ln(phi_vapour) of the pure fluid; zero at saturation."""
    a = 0.45723552892138218*R**2*Tc**2/Pc*alpha
    b = 0.07779607390388846*R*Tc/Pc
    A, B = a*P/(R*T)**2, b*P/(R*T)
    roots = np.roots([1.0, -(1 - B), A - 3*B**2 - 2*B, -(A*B - B**2 - B**3)])
    roots = np.sort(roots[np.abs(roots.imag) < 1e-10].real)
    roots = roots[roots > B]
    if roots.size < 2:
        return np.nan
    return ln_phi_pure(roots[0], A, B) - ln_phi_pure(roots[-1], A, B)


def alpha_at_saturation(T, P, Tc, Pc, guess):
    """alpha(T) for which Peng-Robinson has the saturation pressure P at T."""
    f = lambda al: fugacity_gap(al, T, P, Tc, Pc)
    grid = guess*np.linspace(0.6, 1.6, 201)
    vals = np.array([f(g) for g in grid])
    ok = np.flatnonzero(np.isfinite(vals[:-1]) & np.isfinite(vals[1:]) & (vals[:-1]*vals[1:] < 0))
    if ok.size == 0:
        return np.nan
    k = ok[np.argmin(np.abs(grid[ok] - guess))]
    return brentq(f, grid[k], grid[k + 1], xtol=1e-14)


def main():
    rows = []
    for name, cp_name, nasa in SPECIES:
        Tc, Pc = CP.PropsSI("Tcrit", cp_name), CP.PropsSI("pcrit", cp_name)*1e-5
        omega = CP.PropsSI("acentric", cp_name)
        Tt = CP.PropsSI("Ttriple", cp_name)
        kappa = 0.37464 + 1.54226*omega - 0.26992*omega**2
        Tr = np.linspace(max(Tt/Tc*1.001, 0.45), 0.99, 60)
        x, y = [], []
        for tr in Tr:
            T = tr*Tc
            try:
                psat = CP.PropsSI("P", "T", T, "Q", 0, cp_name)*1e-5
            except ValueError:
                continue
            al = alpha_at_saturation(T, psat, Tc, Pc, (1 + kappa*(1 - np.sqrt(tr)))**2)
            if np.isfinite(al):
                x.append(1 - np.sqrt(tr))
                y.append(np.sqrt(al) - 1)
        x, y = np.array(x), np.array(y)
        c, *_ = np.linalg.lstsq(np.stack([x, x**2, x**3], axis=1), y, rcond=None)
        # quality of the fit: saturation pressure error of the fitted model
        err = []
        for tr in Tr[::6]:
            T = tr*Tc
            xx = 1 - np.sqrt(tr)
            al = (1 + c[0]*xx + c[1]*xx**2 + c[2]*xx**3)**2
            pref = CP.PropsSI("P", "T", T, "Q", 0, cp_name)*1e-5
            try:
                p = brentq(lambda P: fugacity_gap(al, T, P, Tc, Pc), pref*0.8, pref*1.2, xtol=1e-14)
                err.append(abs(p/pref - 1))
            except ValueError:
                pass
        print(f"{name:8s} Tc={Tc:9.3f} K  Pc={Pc:8.3f} bar  omega={omega:8.4f}  kappa={kappa:.4f}  "
              f"MC=({c[0]:.5f}, {c[1]:.5f}, {c[2]:.5f})  max Psat error={100*max(err):.2f} %  (n={len(x)})")
        rows.append((name, nasa, Tc, Pc, omega, *c))

    out = Path(__file__).resolve().parents[1] / "celeste" / "data" / "eos_species.csv"
    with out.open("w") as f:
        f.write("# Peng-Robinson parameters; generated by tools/build_eos_table.py (do not edit by hand)\n")
        f.write("# Tc [K], Pc [bar], omega [-] from the CoolProp reference equations of state;\n")
        f.write("# mc1..mc3: Mathias-Copeman alpha parameters fitted to the saturation pressure curve\n")
        f.write("species,nasa,Tc_K,Pc_bar,omega,mc1,mc2,mc3\n")
        for r in rows:
            f.write(f"{r[0]},\"{r[1]}\",{r[2]:.4f},{r[3]:.5f},{r[4]:.6f},{r[5]:.6f},{r[6]:.6f},{r[7]:.6f}\n")
    print("written", out)


if __name__ == "__main__":
    main()
